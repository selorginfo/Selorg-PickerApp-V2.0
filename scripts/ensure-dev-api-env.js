/**
 * Detect this machine's primary LAN IPv4 and keep it in a local .env file
 * (gitignored). Metro/babel (react-native-dotenv) bake DEV_API_HOST into the
 * JS bundle so physical devices that load Metro via adb reverse (scriptURL =
 * 127.0.0.1) can still reach selorg-service over Wi‑Fi without a hardcoded IP.
 *
 * Safe to re-run: refreshes DEV_API_HOST when DHCP changes; leaves other keys.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const examplePath = path.join(root, '.env.example');

const MANAGED_KEYS = new Set([
  'DEV_API_HOST',
  'EXPO_PUBLIC_DEV_API_HOST',
  'DEV_API_PORT',
  'EXPO_PUBLIC_DEV_API_PORT',
]);

function getLanIPv4() {
  const nets = os.networkInterfaces();
  const preferred = [];
  const other = [];
  for (const name of Object.keys(nets)) {
    for (const net of nets[name] || []) {
      const family = net.family;
      if (family !== 'IPv4' && family !== 4) continue;
      if (net.internal) continue;
      const ip = net.address;
      if (!ip || ip.startsWith('169.254.')) continue;
      if (/^192\.168\.|^10\.|^172\.(1[6-9]|2\d|3[01])\./.test(ip)) {
        preferred.push(ip);
      } else {
        other.push(ip);
      }
    }
  }
  return preferred[0] || other[0] || '';
}

function parseEnv(text) {
  const map = new Map();
  const order = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw;
    if (!line.trim() || line.trim().startsWith('#')) {
      order.push({ type: 'raw', line });
      continue;
    }
    const eq = line.indexOf('=');
    if (eq < 0) {
      order.push({ type: 'raw', line });
      continue;
    }
    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1).trim();
    map.set(key, value);
    order.push({ type: 'kv', key });
  }
  return { map, order };
}

function serializeEnv(map, order) {
  const seen = new Set();
  const lines = [];
  for (const item of order) {
    if (item.type === 'raw') {
      lines.push(item.line);
      continue;
    }
    if (!map.has(item.key) || seen.has(item.key)) continue;
    seen.add(item.key);
    lines.push(`${item.key}=${map.get(item.key)}`);
  }
  for (const [key, value] of map.entries()) {
    if (seen.has(key)) continue;
    lines.push(`${key}=${value}`);
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

const lan = getLanIPv4();
if (!lan) {
  console.warn(
    '[ensure-dev-api-env] No LAN IPv4 found. Physical devices need Wi‑Fi to this PC, or adb reverse tcp:3333.',
  );
}

let text = '';
if (fs.existsSync(envPath)) {
  text = fs.readFileSync(envPath, 'utf8');
} else if (fs.existsSync(examplePath)) {
  text = fs.readFileSync(examplePath, 'utf8');
} else {
  text = [
    '# Local only — do not commit. Regenerated by scripts/ensure-dev-api-env.js',
    'DEV_API_HOST=',
    'DEV_API_PORT=3333',
    '',
  ].join('\n');
}

const { map, order } = parseEnv(text);

// Always refresh managed host/port from this machine so DHCP changes do not
// leave a stale IP in .env (the previous root cause with 192.168.0.9).
if (lan) {
  map.set('DEV_API_HOST', lan);
  map.set('EXPO_PUBLIC_DEV_API_HOST', lan);
}
if (!map.get('DEV_API_PORT')) map.set('DEV_API_PORT', '3333');
if (!map.get('EXPO_PUBLIC_DEV_API_PORT')) {
  map.set('EXPO_PUBLIC_DEV_API_PORT', map.get('DEV_API_PORT') || '3333');
}

// Ensure managed keys appear even on a bare copy of .env.example comments.
for (const key of MANAGED_KEYS) {
  if (!map.has(key)) continue;
  if (!order.some(item => item.type === 'kv' && item.key === key)) {
    order.push({ type: 'kv', key });
  }
}

fs.writeFileSync(envPath, serializeEnv(map, order), 'utf8');
console.log(
  `[ensure-dev-api-env] DEV_API_HOST=${map.get('DEV_API_HOST') || '(empty)'} DEV_API_PORT=${map.get('DEV_API_PORT')}`,
);

module.exports = { getLanIPv4, envPath };
